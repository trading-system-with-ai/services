"""Event Intelligence Core — pure domain layer (event spec §5-§7, §10-§13,
§15, §67, §78; audit §5.1).

Deterministic, stdlib-only, **no I/O**. The gateway seam
(`apps/gateway/event_calendar.py`) and the provider registry
(`libs/event_calendar/`) call into this package; nothing here imports them.
That direction is load-bearing and mechanically checked — audit §7.4 pins a
static guard asserting no module under this package imports
`libs.market_data` or `libs.event_calendar`, which is what proves the
as-of-scoped analysis layer cannot reach a live API.

Contents:

- :mod:`.taxonomy` — natural keys, ET/UTC time handling, session
  classification against the market calendar, lifecycle windows.
- :mod:`.models` — :class:`Event` / :class:`EventCandidate` value objects,
  §78 source precedence, the :func:`merge` reconciliation rules and the §15
  previous-comparable matcher.
- :mod:`.importance` — the transparent additive importance model (§13).
- :mod:`.reaction` — as-of bar gating (§14/§96), previous-event reaction
  windows (§17), the |move| history distribution (§19/§64) and the pre-event
  price context (§31/§32).
- :mod:`.fundamentals` — the point-in-time statement gate on
  ``acceptance_datetime`` (§7/§85/§96), the §28 metric snapshot, the §29
  previous-vs-current change table and the §30 own-history valuation context.
- :mod:`.news_intel` — the §22 news pipeline: normalisation,
  deduplication, story clustering, materiality, novelty, source quality,
  time decay and the explainable §25 evidence score.
- :mod:`.replay` — the §17 minute-bar reaction (session-chosen anchors), the
  §20 replay bundle, the §60 multi-event history table and the §15
  previous-event linkage batch.
"""
